#!/usr/bin/env bash
# Guided installer for a Debian/Ubuntu or RHEL-family Linux host.
#   1. installs Node.js 20+ if missing
#   2. npm install
#   3. asks for every setting and writes .env
#   4. runs the verification (npm run check)
#   5. optionally installs the systemd unit
set -euo pipefail
cd "$(dirname "$0")/.."
APP_DIR="$(pwd)"

say()  { printf '\n\033[1;36m%s\033[0m\n' "$*"; }
ask()  { # ask VAR "prompt" "default"
  local var="$1" prompt="$2" def="${3:-}" val
  if [ -n "$def" ]; then read -r -p "$prompt [$def]: " val; val="${val:-$def}"; else read -r -p "$prompt: " val; fi
  printf -v "$var" '%s' "$val"
}
asksecret() { local var="$1" prompt="$2" val; read -r -s -p "$prompt: " val; echo; printf -v "$var" '%s' "$val"; }

say "1/5  Node.js"
if ! command -v node >/dev/null 2>&1 || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]; then
  echo "Node.js 20+ not found. Installing Node.js 22 LTS via NodeSource..."
  if command -v apt-get >/dev/null; then
    curl -fsSL https://deb.nodesource.com/setup_22.x | sudo -E bash -
    sudo apt-get install -y nodejs
  elif command -v dnf >/dev/null; then
    curl -fsSL https://rpm.nodesource.com/setup_22.x | sudo bash -
    sudo dnf install -y nodejs
  else
    echo "Install Node.js 20+ manually (https://nodejs.org) and re-run."; exit 1
  fi
fi
echo "node $(node -v), npm $(npm -v)"

say "2/5  Dependencies"
npm install --omit=dev

say "3/5  Configuration"
if [ -f .env ]; then
  read -r -p ".env already exists. Overwrite it? [y/N] " yn
  [[ "$yn" =~ ^[Yy] ]] || { echo "Keeping existing .env"; SKIP_ENV=1; }
fi
if [ -z "${SKIP_ENV:-}" ]; then
  echo "Answer each question; press Enter to accept the default in [brackets]."
  echo
  echo "--- Organisation ---"
  ask ORG_NAME    "Organisation name shown on the page and in e-mails" "My Company"
  ask IT_CONTACT  "How users reach IT (shown when a reset is refused)" "IT helpdesk"
  ask PUBLIC_URL  "Public URL users will open" "http://$(hostname -I 2>/dev/null | awk '{print $1}'):3800"
  ask PORT        "Port to listen on" "3800"
  ask HOST        "Bind address (127.0.0.1 if nginx sits in front, else 0.0.0.0)" "0.0.0.0"
  echo
  echo "--- Active Directory ---"
  ask AD_HOST     "Domain controller hostname (must match its certificate, e.g. dc1.corp.example.com)"
  ask AD_PORT     "LDAPS port" "636"
  ask AD_BIND_DN  "Service account login (UPN form, e.g. svc-pwreset@corp.example.com)"
  asksecret AD_BIND_PASSWORD "Service account password"
  ask AD_BASE_DN  "OU that contains the users allowed to self-reset (e.g. OU=Staff,DC=corp,DC=example,DC=com)"
  ask AD_RECOVERY_MAIL_ATTR "AD attribute holding the recovery e-mail" "mail"
  ask AD_PROTECTED_DN_REGEX "Regex of OUs that must never be reset here" "OU=Admins|OU=Service Accounts"
  ask AD_PROTECTED_GROUPS "Protected groups (comma separated)" "Domain Admins,Enterprise Admins,Administrators,Schema Admins,Account Operators"
  ask AD_MUST_CHANGE_AT_LOGON "Force 'change password at next logon' after reset? (true/false)" "false"
  ask AD_CA_CERT  "Path to your internal CA certificate (PEM). Leave empty if the DC cert is publicly trusted" ""
  echo
  echo "--- Outgoing mail (SMTP) ---"
  ask SMTP_HOST   "SMTP server" "smtp.office365.com"
  ask SMTP_PORT   "SMTP port" "587"
  ask SMTP_SECURE "Implicit TLS? (true for 465, false for 587)" "false"
  ask SMTP_USER   "SMTP username (leave empty for no auth)" ""
  if [ -n "$SMTP_USER" ]; then asksecret SMTP_PASSWORD "SMTP password"; else SMTP_PASSWORD=""; fi
  ask SMTP_FROM   "From address" "IT Self Service <${SMTP_USER:-noreply@example.com}>"
  echo
  echo "--- Safety ---"
  ask RESET_DRY_RUN "Start in DRY RUN (no AD writes) until you have verified end to end? (true/false)" "true"

  cat > .env <<ENV
# Generated by scripts/setup.sh on $(date -Is). See .env.example for the meaning of each key.
HOST=$HOST
PORT=$PORT
NODE_ENV=production
PUBLIC_URL=$PUBLIC_URL
TRUST_PROXY=false

AD_HOST=$AD_HOST
AD_PORT=$AD_PORT
AD_BIND_DN=$AD_BIND_DN
AD_BIND_PASSWORD=$AD_BIND_PASSWORD
AD_BASE_DN=$AD_BASE_DN
AD_RECOVERY_MAIL_ATTR=$AD_RECOVERY_MAIL_ATTR
AD_PROTECTED_DN_REGEX=$AD_PROTECTED_DN_REGEX
AD_PROTECTED_GROUPS=$AD_PROTECTED_GROUPS
AD_MUST_CHANGE_AT_LOGON=$AD_MUST_CHANGE_AT_LOGON
AD_TLS_REJECT_UNAUTHORIZED=true
AD_CA_CERT=$AD_CA_CERT
AD_TIMEOUT_MS=10000

SMTP_HOST=$SMTP_HOST
SMTP_PORT=$SMTP_PORT
SMTP_SECURE=$SMTP_SECURE
SMTP_USER=$SMTP_USER
SMTP_PASSWORD=$SMTP_PASSWORD
SMTP_FROM=$SMTP_FROM
ORG_NAME=$ORG_NAME
IT_CONTACT=$IT_CONTACT

OTP_TTL_MIN=10
OTP_MAX_ATTEMPTS=5
OTP_SENDS_PER_15MIN=3
CHALLENGES_PER_IP_15MIN=10
RESETS_PER_DAY=3
PASSWORD_LENGTH=14

RESET_DRY_RUN=$RESET_DRY_RUN
OTP_DEBUG_LOG=false
AUDIT_LOG=$APP_DIR/data/audit.jsonl
ENV
  chmod 600 .env
  mkdir -p data
  echo "Wrote .env (mode 600)."
fi

say "4/5  Verification"
read -r -p "Username of a NORMAL (non-admin) test account to look up, or Enter to skip: " TESTUSER
read -r -p "E-mail address to send a test message to, or Enter to skip: " TESTMAIL
ARGS=()
[ -n "$TESTUSER" ] && ARGS+=(--user "$TESTUSER")
[ -n "$TESTMAIL" ] && ARGS+=(--mail "$TESTMAIL")
node scripts/check.js "${ARGS[@]}" || { echo; echo "Fix the failed checks (edit .env) and run:  npm run check -- ${ARGS[*]}"; exit 1; }

say "5/5  systemd service"
read -r -p "Install and start as a systemd service now? [Y/n] " yn
if [[ ! "$yn" =~ ^[Nn] ]]; then
  SVC_USER="$(id -un)"
  sed -e "s#__APP_DIR__#$APP_DIR#g" -e "s#__USER__#$SVC_USER#g" -e "s#__NODE__#$(command -v node)#g" \
      deploy/ad-self-service.service | sudo tee /etc/systemd/system/ad-self-service.service >/dev/null
  sudo systemctl daemon-reload
  sudo systemctl enable --now ad-self-service
  sleep 2
  sudo systemctl --no-pager --lines=5 status ad-self-service || true
  echo
  echo "Open: $(grep ^PUBLIC_URL .env | cut -d= -f2-)"
  echo "Health: curl -s http://127.0.0.1:$(grep ^PORT .env | cut -d= -f2-)/api/health"
else
  echo "Start manually with:  npm start"
fi

echo
echo "NEXT: walk through docs/INSTALL.md §7 (end-to-end test), then set RESET_DRY_RUN=false in .env and restart:"
echo "      sudo systemctl restart ad-self-service"
